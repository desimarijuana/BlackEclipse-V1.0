// Gateway-backed market-read + pure quant-metric node contracts.
//
// Split out of `registry.ts` to keep that file inside its size budget; the
// definitions are still declared ONCE and re-exported into the one registry
// array. The Python runtime declares the same contracts in
// `graph_runtime/market_read_nodes.py` and `graph_runtime/quant_metrics_nodes.py`
// and the parity suite compares them field by field.

import { z } from 'zod';
import type { NodeDefinition, PortDef } from './types';

function port(p: PortDef): PortDef {
  return { kind: 'data', ...p };
}

const FRESHNESS = ['realtime', 'intraday', 'daily', 'slow', 'any'] as const;
const INPUT_KINDS = ['returns', 'prices'] as const;

function symbolInputs(): PortDef[] {
  return [port({ id: 'symbol', name: 'Symbol', type: 'string', optional: true })];
}

function readOutputs(valueId: string, valueName: string): PortDef[] {
  return [
    port({ id: valueId, name: valueName, type: 'object' }),
    // A compact digest so the node card / Output tab is readable.
    port({ id: 'summary', name: 'Summary', type: 'object' }),
    port({ id: 'provenance', name: 'Provenance', type: 'evidence' }),
  ];
}

