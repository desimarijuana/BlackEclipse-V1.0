#!/usr/bin/env node
/**
 * Harness scorecard with evidence (Round 5 / C0).
 *
 * A dimension is only a number when a runnable gate backs it. This script reads
 * `docs/harness/scorecard.json`, verifies every evidence path exists, and emits
 * `docs/harness/scorecard.md`.
 *
 * Usage:
 *   node scripts/harness-scorecard.js           # report (writes the markdown)
 *   node scripts/harness-scorecard.js --check   # fail if the markdown is stale
 *   node scripts/harness-scorecard.js --strict  # fail if ANY dimension is not "measured"
 */

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const MANIFEST = path.join(ROOT, "docs", "harness", "scorecard.json");
const OUTPUT = path.join(ROOT, "docs", "harness", "scorecard.md");
const VALID = new Set(["measured", "partial", "unmeasured"]);

function readManifest() {
  if (!fs.existsSync(MANIFEST)) {
    console.error(`[scorecard] missing manifest: ${path.relative(ROOT, MANIFEST)}`);
    process.exit(1);
  }
  try {
    return JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  } catch (error) {
    console.error(`[scorecard] invalid JSON: ${error.message}`);
    process.exit(1);
  }
}

function verify(manifest) {
  const problems = [];
  const dimensions = Array.isArray(manifest.dimensions) ? manifest.dimensions : [];
  if (dimensions.length === 0) problems.push("no dimensions declared");
  for (const dimension of dimensions) {
    const id = dimension.id || "(unnamed)";
    if (!VALID.has(dimension.status)) {
      problems.push(`${id}: status must be measured|partial|unmeasured`);
    }
    if (!Array.isArray(dimension.evidence) || dimension.evidence.length === 0) {
      if (dimension.status !== "unmeasured") {
        problems.push(`${id}: ${dimension.status} needs at least one evidence path`);
      }
      continue;
    }
    for (const evidence of dimension.evidence) {
      const target = path.join(ROOT, evidence);
      if (!fs.existsSync(target)) {
        problems.push(`${id}: evidence not found: ${evidence}`);
      }
    }
    if (dimension.status === "measured" && !dimension.metric) {
      problems.push(`${id}: measured requires a metric { value, source }`);
    }
  }
  return { dimensions, problems };
}

function render(manifest, dimensions) {
  const lines = [];
  lines.push("---");
  lines.push("title: Harness Scorecard (evidence-backed)");
  lines.push("status: Generated");
  lines.push(`last-verified: ${manifest.generated || new Date().toISOString().slice(0, 10)}`);
  lines.push("---");
  lines.push("");
  lines.push("# Harness Scorecard");
  lines.push("");
  lines.push("Generated by `node scripts/harness-scorecard.js`. Do not edit by hand.");
  lines.push("A dimension is **measured** only when every evidence path exists and a metric is recorded;");
  lines.push("`partial` and `unmeasured` are honest states, not zeros.");
  lines.push("");
  lines.push("| Dimension | Weight | Target | Status | Metric | Evidence |");
  lines.push("|---|---:|---:|---|---|---|");
  for (const dimension of dimensions) {
    const metric = dimension.metric
      ? `${dimension.metric.value} (${dimension.metric.source || "source not named"})`
      : "—";
    const evidence = (dimension.evidence || []).map((item) => `\`${item}\``).join("<br>") || "—";
    lines.push(
      `| ${dimension.label || dimension.id} | ${dimension.weight ?? "—"} | ${dimension.target ?? "—"} | **${dimension.status}** | ${metric} | ${evidence} |`,
    );
  }
  lines.push("");
  if (manifest.note) {
    lines.push(manifest.note);
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

function main() {
  const args = new Set(process.argv.slice(2));
  const manifest = readManifest();
  const { dimensions, problems } = verify(manifest);
  if (problems.length > 0) {
    console.error("[scorecard] FAILED:");
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }

  const markdown = render(manifest, dimensions);
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
  if (args.has("--check")) {
    if (current !== markdown) {
      console.error("[scorecard] stale: run `node scripts/harness-scorecard.js` and commit the result");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, markdown, "utf8");
  }

  const counts = dimensions.reduce((acc, dimension) => {
    acc[dimension.status] = (acc[dimension.status] || 0) + 1;
    return acc;
  }, {});
  console.log(
    `[scorecard] ${dimensions.length} dimensions — measured ${counts.measured || 0}, ` +
      `partial ${counts.partial || 0}, unmeasured ${counts.unmeasured || 0}`,
  );

  if (args.has("--strict")) {
    const unmeasured = dimensions.filter((dimension) => dimension.status !== "measured");
    if (unmeasured.length > 0) {
      console.error(
        `[scorecard] strict gate FAILED: ${unmeasured.map((d) => d.id).join(", ")} not measured`,
      );
      process.exit(1);
    }
  }
}

main();
