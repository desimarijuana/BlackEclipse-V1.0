"""The seeded quantitative-method knowledge base.

These are well-established methods, stored as formal specifications rather than
strategy templates. The catalog is deliberately conservative:

- every equation names a real publication (or the standard definition);
- `best_regimes` / applicability are priors, never measured edge claims;
- `implementationStatus` says what Eclipse can actually run today;
- nothing here claims a profit.

The catalog is data. Adding a method is a data edit or a controlled research
registration, never a new intent-classifier branch.
"""

from __future__ import annotations

from typing import Any

from .schema import normalize_spec


def _ref(citation: str, year: int | None = None) -> dict[str, Any]:
    out: dict[str, Any] = {"citation": citation}
    if year is not None:
        out["year"] = year
    return out


def _eq(latex: str, variables: list[str], citation: str, section: str = "") -> dict[str, Any]:
    return {"latex": latex, "variables": variables,
            "source": {"citation": citation, "section": section}}


def _horizons(frequencies: list[str]) -> list[str]:
    out: list[str] = []
    for frequency in frequencies:
        f = str(frequency or "").lower()
        if any(token in f for token in ("tick", "intraday", "minute", "hour")):
            for item in ("intraday", "swing"):
                if item not in out:
                    out.append(item)
        elif any(token in f for token in ("daily", "day")):
            for item in ("swing", "position"):
                if item not in out:
                    out.append(item)
        elif any(token in f for token in ("weekly", "week", "monthly", "month")):
            for item in ("position", "long-term"):
                if item not in out:
                    out.append(item)
    return out or ["swing"]


def _m(
    method_id: str,
    name: str,
    family: str,
    objective: list[str],
    instruments: list[str],
    frequencies: list[str],
    inputs: list[tuple[str, str]],
    parameters: list[dict[str, Any]],
    equations: list[dict[str, Any]],
    estimation: str,
    assumptions: list[str],
    outputs: list[str],
    validation: list[str],
    limitations: list[str],
    references: list[dict[str, Any]],
    *,
    complexity: int = 3,
    evidence_level: int = 4,
    implementation: str = "none",
    aliases: list[str] | None = None,
    horizons: list[str] | None = None,
    notes: str = "",
) -> dict[str, Any]:
    citation = references[0]["citation"] if references else "standard definition"
    return normalize_spec({
        "methodId": method_id,
        "name": name,
        "family": family,
        "version": "1.0.0",
        "aliases": aliases or [],
        "objective": objective,
        "instruments": instruments,
        "frequencies": frequencies,
        "horizons": horizons or _horizons(frequencies),
        "inputs": [{"name": n, "frequency": f, "required": True} for n, f in inputs],
        "parameters": parameters,
        "equations": equations,
        "estimation": {"method": estimation},
        "assumptions": assumptions,
        "outputs": outputs,
        "validation": validation,
        "limitations": limitations,
        "references": references,
        "provenance": {
            "literatureIds": [],
            "implementationIds": [],
            "confidence": "high",
            "source": "catalog",
            "citation": citation,
            "notes": notes,
        },
        "unresolved": [],
        "implementationStatus": implementation,
        "reproductionStatus": "none",
        "lifecycleStatus": "reviewed",
        "complexity": complexity,
        "evidenceLevel": evidence_level,
    })


