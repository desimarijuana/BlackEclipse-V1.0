def catalog_by_id() -> dict[str, dict[str, Any]]:
    return {m["methodId"]: dict(m) for m in CATALOG}


def get_catalog_method(method_id: str) -> dict[str, Any] | None:
    method = catalog_by_id().get(str(method_id))
    return dict(method) if method else None


def list_catalog(*, family: str | None = None, objective: str | None = None) -> list[dict[str, Any]]:
    out = []
    for method in CATALOG:
        if family and method.get("family") != family:
            continue
        if objective and objective not in (method.get("objective") or []):
            continue
        out.append(dict(method))
    return out


