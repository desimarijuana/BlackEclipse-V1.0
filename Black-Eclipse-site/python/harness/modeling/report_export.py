"""Model deliverables beyond the workbook: PDF memo, Word memo and PowerPoint deck."""

from __future__ import annotations

import io
from typing import Any

from ..documents.authoring import build_docx
from ..documents.reporting import build_pdf
from .contracts import ModelError, ModelResult

MAX_TABLE_ROWS = 60
MAX_TABLE_COLS = 10


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        if abs(value) >= 1000:
            return f"{value:,.1f}"
        return f"{value:,.4f}"
    return str(value)


def _table_block(columns: list[Any], rows: list[dict[str, Any]]) -> dict[str, Any] | None:
    if not columns:
        return None
    headers = [str(column) for column in columns[:MAX_TABLE_COLS]]
    body: list[list[Any]] = []
    for row in rows[:MAX_TABLE_ROWS]:
        values = list(row.get("values") or [])
        if len(values) == len(columns):
            body.append([_fmt(value) for value in values[:MAX_TABLE_COLS]])
        else:
            body.append([row.get("label") or ""] + [_fmt(value) for value in values[: max(0, MAX_TABLE_COLS - 1)]])
    return {"type": "table", "headers": headers, "rows": body}


def model_blocks(result: ModelResult) -> list[dict[str, Any]]:
    blocks: list[dict[str, Any]] = [
        {"type": "heading", "text": "Executive summary", "level": 1},
        {"type": "paragraph", "text": (
            f"{result.company} · {result.kind.replace('_', ' ')} model · "
            f"{result.units} · {result.currency}. "
            f"Model checks: {'PASS' if result.checks_pass() else 'FAIL'}."
        )},
    ]
    key_metrics = [
        {"label": label, "values": [value], "kind": "calc"}
        for label, value in (
            ("Enterprise value", result.meta.get("enterpriseValue")),
            ("Equity value", result.meta.get("equityValue")),
            ("Value per share", result.meta.get("valuePerShare")),
            ("WACC", result.meta.get("wacc")),
            ("IRR", result.meta.get("irr")),
            ("MOIC", result.meta.get("moic")),
        )
        if value is not None
    ]
    if key_metrics:
        blocks.append({"type": "heading", "text": "Key outputs", "level": 2})
        blocks.append(_table_block(["Metric", "Value"], key_metrics) or {})
    for section_name, section in list(result.sections.items())[:8]:
        table = _table_block(section.get("columns") or [], section.get("rows") or [])
        if table is None:
            continue
        blocks.append({"type": "heading", "text": section_name, "level": 2})
        blocks.append(table)
    blocks.append({"type": "heading", "text": "Model checks", "level": 2})
    checks = [{"label": check.name, "values": [check.status, check.detail], "kind": "check"} for check in result.checks]
    blocks.append({"type": "table", "headers": ["Check", "Status", "Detail"],
                   "rows": [[check.name, check.status, check.detail] for check in result.checks]})
    if result.warnings:
        blocks.append({"type": "heading", "text": "Warnings", "level": 2})
        blocks.append({"type": "bullets", "items": list(result.warnings)})
    return [block for block in blocks if block]


def build_model_pdf(spec: dict[str, Any], result: ModelResult) -> bytes:
    return build_pdf(
        model_blocks(result),
        title=f"{result.company} — {result.kind.replace('_', ' ').title()}",
        subtitle=f"{result.units} · {result.currency} · Generated by Eclipse",
        footer="Eclipse financial model",
    )


def build_model_docx(spec: dict[str, Any], result: ModelResult) -> bytes:
    return build_docx(
        model_blocks(result),
        title=f"{result.company} — {result.kind.replace('_', ' ').title()}",
    )


def build_model_pptx(spec: dict[str, Any], result: ModelResult) -> bytes:
    try:
        from pptx import Presentation  # noqa: PLC0415
        from pptx.util import Inches, Pt  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        raise ModelError(
            "PPTX_LIBRARY_MISSING",
            "python-pptx is not installed, so the model deck cannot be written",
        ) from exc

    presentation = Presentation()
    cover_layout = presentation.slide_layouts[0]
    cover = presentation.slides.add_slide(cover_layout)
    cover.shapes.title.text = f"{result.company} — {result.kind.replace('_', ' ').title()}"
    if len(cover.placeholders) > 1:
        cover.placeholders[1].text = (
            f"{result.units} · {result.currency}\n"
            f"Model checks: {'PASS' if result.checks_pass() else 'FAIL'}"
        )

    summary_layout = presentation.slide_layouts[1]
    summary = presentation.slides.add_slide(summary_layout)
    summary.shapes.title.text = "Executive summary"
    body = summary.placeholders[1].text_frame
    body.clear()
    lines = [
        f"Checks: {'PASS' if result.checks_pass() else 'FAIL'}",
        *[
            f"{label}: {_fmt(value)}"
            for label, value in (
                ("Enterprise value", result.meta.get("enterpriseValue")),
                ("Equity value", result.meta.get("equityValue")),
                ("Value per share", result.meta.get("valuePerShare")),
                ("WACC", result.meta.get("wacc")),
                ("IRR", result.meta.get("irr")),
                ("MOIC", result.meta.get("moic")),
            )
            if value is not None
        ],
    ]
    for index, line in enumerate(lines):
        paragraph = body.paragraphs[0] if index == 0 else body.add_paragraph()
        paragraph.text = line

    title_only = presentation.slide_layouts[5] if len(presentation.slide_layouts) > 5 else summary_layout
    for section_name, section in list(result.sections.items())[:8]:
        columns = list(section.get("columns") or [])
        rows = list(section.get("rows") or [])
        if not columns or not rows:
            continue
        slide = presentation.slides.add_slide(title_only)
        slide.shapes.title.text = section_name
        headers = [str(column) for column in columns[:MAX_TABLE_COLS]]
        body_rows = rows[: min(12, MAX_TABLE_ROWS)]
        table_shape = slide.shapes.add_table(
            len(body_rows) + 1, len(headers), Inches(0.4), Inches(1.5), Inches(9.2), Inches(4.8),
        )
        table = table_shape.table
        for column_index, header in enumerate(headers):
            cell = table.cell(0, column_index)
            cell.text = header
            for paragraph in cell.text_frame.paragraphs:
                for run in paragraph.runs:
                    run.font.size = Pt(10)
                    run.font.bold = True
        for row_index, row in enumerate(body_rows, start=1):
            values = list(row.get("values") or [])
            if len(values) != len(columns):
                values = [row.get("label") or ""] + values
            for column_index in range(len(headers)):
                cell = table.cell(row_index, column_index)
                cell.text = _fmt(values[column_index]) if column_index < len(values) else ""
                for paragraph in cell.text_frame.paragraphs:
                    for run in paragraph.runs:
                        run.font.size = Pt(9)

    checks_slide = presentation.slides.add_slide(title_only)
    checks_slide.shapes.title.text = "Model checks"
    check_rows = len(result.checks) + 1
    table_shape = checks_slide.shapes.add_table(
        check_rows, 3, Inches(0.4), Inches(1.5), Inches(9.2), Inches(4.8),
    )
    table = table_shape.table
    for index, header in enumerate(("Check", "Status", "Detail")):
        table.cell(0, index).text = header
    for row_index, check in enumerate(result.checks, start=1):
        table.cell(row_index, 0).text = check.name
        table.cell(row_index, 1).text = check.status
        table.cell(row_index, 2).text = check.detail
    for row in table.rows:
        for cell in row.cells:
            for paragraph in cell.text_frame.paragraphs:
                for run in paragraph.runs:
                    run.font.size = Pt(9)

    buffer = io.BytesIO()
    presentation.save(buffer)
    return buffer.getvalue()


def build_model_report(fmt: str, spec: dict[str, Any], result: ModelResult) -> bytes:
    key = (fmt or "").strip().casefold()
    if key == "pdf":
        return build_model_pdf(spec, result)
    if key == "docx":
        return build_model_docx(spec, result)
    if key == "pptx":
        return build_model_pptx(spec, result)
    raise ModelError("MODEL_FORMAT_UNSUPPORTED", f"unsupported model report format {fmt!r}")


__all__ = ["build_model_docx", "build_model_pdf", "build_model_pptx", "build_model_report", "model_blocks"]
