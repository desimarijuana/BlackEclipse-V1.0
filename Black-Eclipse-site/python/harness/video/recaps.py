"""Market-recap videos: a bound storyboard built from symbols (Phase 8).

A recap is the natural RECURRING video: a few symbols, their last price and day
change, and one daily candle chart. This module builds that storyboard as a
`schemaVersion 3` spec with DATA BINDINGS — every figure resolves through the
existing Market Data Gateway at render time, so a recap can never show an
authored or invented number. Creating the project is cheap; rendering stays the
ordinary queued job (`render_draft`/`render_final`/`preview_project`).

Scheduling never gets its own timer: the `daily-market-recap-video` job
template (jobs/templates.py) runs the ordinary agent runtime on a cron, and the
agent uses the video tools. Limits are explicit: 1-5 symbols (a 12-scene
storyboard cap), daily candles.
"""

from __future__ import annotations

from typing import Any, Optional

from .models import VideoError
from .service import VideoService
from .spec import validate_storyboard

MAX_RECAP_SYMBOLS = 5
MAX_SYMBOL_LENGTH = 12
DEFAULT_RECAP_TITLE = "MARKET RECAP"
RECAP_CANDLE_COUNT = 30


def build_recap_spec(
    *, symbols: Any, title: Optional[str] = None, subtitle: Optional[str] = None,
) -> dict[str, Any]:
    """The bound storyboard for a market recap (validated against the schema)."""
    clean_symbols = _clean_symbols(symbols)
    clean_title = str(title or DEFAULT_RECAP_TITLE).strip()[:80] or DEFAULT_RECAP_TITLE
    clean_subtitle = str(subtitle).strip()[:120] if subtitle else None
    scenes: list[dict[str, Any]] = [
        {
            "type": "intro", "durationSeconds": 3, "title": clean_title,
            **({"subtitle": clean_subtitle} if clean_subtitle else {}),
        },
    ]
    for index, symbol in enumerate(clean_symbols):
        scenes.append({
            "type": "metric", "durationSeconds": 4,
            "transition": "fade" if index else "cut",
            "title": f"{symbol} TODAY",
            "metrics": [
                {"label": "Last price", "source": {"symbol": symbol, "field": "price"}},
                {"label": "Volume", "source": {"symbol": symbol, "field": "volume"}},
            ],
        })
        if index == 0:
            scenes.append({
                "type": "candlestick", "durationSeconds": 5, "transition": "fade",
                "title": f"{symbol} · DAILY", "symbol": symbol,
                "data": {"symbol": symbol, "interval": "1d", "count": RECAP_CANDLE_COUNT},
            })
    scenes.append({
        "type": "outro", "durationSeconds": 3, "transition": "fade",
        "title": "BLACK ECLIPSE",
    })
    spec = {"schemaVersion": 3, "format": "landscape", "scenes": scenes}
    problems = validate_storyboard(spec)
    if problems:
        # A recap is generated by us; a problem here is a code bug, reported
        # honestly and never rendered as a half-valid storyboard.
        raise VideoError("INVALID_SPEC", "; ".join(problems))
    return spec


def create_recap_project(
    service: VideoService, *, symbols: Any, title: Optional[str] = None,
    subtitle: Optional[str] = None,
) -> dict[str, Any]:
    """Create a recap project from bound scenes. Nothing renders here."""
    spec = build_recap_spec(symbols=symbols, title=title, subtitle=subtitle)
    name = str(title or DEFAULT_RECAP_TITLE).strip()[:200] or DEFAULT_RECAP_TITLE
    return service.create_project(name=name, kind="storyboard", spec=spec)


def _clean_symbols(symbols: Any) -> list[str]:
    if not isinstance(symbols, list) or not symbols:
        raise VideoError(
            "INVALID_INPUT", f"a recap needs 1-{MAX_RECAP_SYMBOLS} symbols"
        )
    cleaned: list[str] = []
    for raw in symbols:
        symbol = str(raw or "").strip().upper()
        if not symbol:
            continue
        if len(symbol) > MAX_SYMBOL_LENGTH or any(ch.isspace() for ch in symbol):
            raise VideoError(
                "INVALID_INPUT",
                f"invalid symbol {raw!r} (1-{MAX_SYMBOL_LENGTH} characters, no spaces)",
            )
        if symbol not in cleaned:
            cleaned.append(symbol)
    if not cleaned:
        raise VideoError("INVALID_INPUT", "a recap needs at least one symbol")
    if len(cleaned) > MAX_RECAP_SYMBOLS:
        raise VideoError(
            "INVALID_INPUT",
            f"a recap takes at most {MAX_RECAP_SYMBOLS} symbols (got {len(cleaned)})",
        )
    return cleaned


__all__ = [
    "DEFAULT_RECAP_TITLE",
    "MAX_RECAP_SYMBOLS",
    "build_recap_spec",
    "create_recap_project",
]
