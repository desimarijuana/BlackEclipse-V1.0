"""Report rendering — the PDF writer and the neutral report contract.

The document authoring module already writes Word, Excel, PowerPoint and text
formats. This module adds the missing PDF output without a new dependency: the
vendored Matplotlib PDF backend lays out the same neutral blocks (headings,
paragraphs, bullets, tables and page breaks) as real, paginated pages.

The output is a computed deliverable. It is registered in the Artifact Center
by `report_tools.py`; nothing here touches the network or the user's files.
"""

from __future__ import annotations

import io
import textwrap
from typing import Any, Optional, Sequence

from .authoring import (
    FORMAT_EXTENSION,
    FORMAT_MIME,
    DocumentError,
    _as_text,
    _rows_of,
    build,
    canonical_format,
    slug_filename,
)

PDF_MIME = "application/pdf"
REPORT_FORMATS: tuple[str, ...] = ("pdf", "docx", "xlsx", "pptx", "markdown", "txt")
PAGE_SIZE = (8.5, 11.0)
_MARGIN_LEFT = 0.08
_MARGIN_RIGHT = 0.92
_TOP = 0.93
_BOTTOM = 0.07
_LINE = 0.018
_MAX_CELL_CHARS = 120


def report_extension(fmt: str) -> str:
    if (fmt or "").strip().casefold() == "pdf":
        return "pdf"
    return FORMAT_EXTENSION.get(canonical_format(fmt), "pdf")


def report_mime(fmt: str) -> str:
    return PDF_MIME if (fmt or "").strip().casefold() == "pdf" else FORMAT_MIME[canonical_format(fmt)]


def build_report(
    fmt: str,
    *,
    title: str = "",
    subtitle: str = "",
    blocks: Optional[Sequence[dict[str, Any]]] = None,
    sheets: Optional[Sequence[dict[str, Any]]] = None,
    footer: str = "Generated by Eclipse",
) -> bytes:
    key = (fmt or "").strip().casefold()
    if key == "pdf":
        return build_pdf(blocks or [], title=title, subtitle=subtitle, footer=footer)
    if key in ("markdown", "md", "txt", "text", "docx", "xlsx", "pptx"):
        return build(key, title=title, blocks=blocks, sheets=sheets)
    raise DocumentError("DOCUMENT_FORMAT_UNSUPPORTED", f"unsupported report format {fmt!r}")


def build_pdf(
    blocks: Sequence[dict[str, Any]],
    *,
    title: str = "",
    subtitle: str = "",
    footer: str = "Generated by Eclipse",
) -> bytes:
    try:
        from matplotlib.backends.backend_pdf import PdfPages  # noqa: PLC0415
        from matplotlib.figure import Figure  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        raise DocumentError(
            "REPORT_RENDER_UNAVAILABLE",
            "Matplotlib is not installed, so PDF reports cannot be rendered",
        ) from exc

    buffer = io.BytesIO()
    try:
        pdf = PdfPages(buffer)
        page_number = 0

        def _new_figure() -> tuple[Any, Any]:
            figure = Figure(figsize=PAGE_SIZE, dpi=120)
            axes = figure.add_axes([0, 0, 1, 1])
            axes.set_axis_off()
            return figure, axes

        figure, axes = _new_figure()
        cursor = {"y": _TOP}
        page = {"n": 0}

        def _save() -> None:
            nonlocal page_number
            if page["n"] <= 0:
                return
            page_number += 1
            axes.text(
                0.5, 0.03, f"{footer} · page {page_number}",
                ha="center", va="bottom", fontsize=7.5, color="#6b7280",
                transform=axes.transAxes,
            )
            pdf.savefig(figure)

        def _new_page() -> None:
            nonlocal figure, axes
            _save()
            figure, axes = _new_figure()
            page["n"] += 1
            cursor["y"] = _TOP

        _new_page()

        def _space(height: float) -> None:
            if cursor["y"] - height < _BOTTOM:
                _new_page()

        def _text(
            text: str,
            *,
            size: float = 10.0,
            weight: str = "normal",
            indent: float = 0.0,
            width: int = 92,
            color: str = "#111827",
            gap: float = 0.006,
        ) -> None:
            value = _as_text(text).strip()
            if not value:
                return
            lines = textwrap.wrap(value, width=max(20, width)) or [value]
            line_height = _LINE * (size / 10.0)
            for line in lines:
                _space(line_height)
                axes.text(
                    _MARGIN_LEFT + indent, cursor["y"], line,
                    ha="left", va="top", fontsize=size, weight=weight,
                    color=color, transform=axes.transAxes,
                )
                cursor["y"] -= line_height
            cursor["y"] -= gap

        def _heading(text: str, level: int) -> None:
            size = {1: 16.0, 2: 13.5, 3: 11.5}.get(max(1, min(3, level)), 11.0)
            cursor["y"] -= 0.01
            _space(0.05)
            _text(text, size=size, weight="bold", width=70, gap=0.012)

        def _table(headers: Sequence[Any], rows: Sequence[Any]) -> None:
            columns = len(headers) or (
                len(rows[0]) if rows and isinstance(rows[0], (list, tuple)) else 0
            )
            if columns <= 0:
                return
            data: list[list[str]] = []
            for row in list(rows)[:40]:
                values = list(row) if isinstance(row, (list, tuple)) else [row]
                data.append([
                    _as_text(values[i] if i < len(values) else "")[:_MAX_CELL_CHARS]
                    for i in range(columns)
                ])
            height = min(0.55, 0.035 * (len(data) + 1) + 0.02)
            _space(height + 0.03)
            table = axes.table(
                cellText=data,
                colLabels=[_as_text(header)[:_MAX_CELL_CHARS] for header in list(headers)[:columns]],
                loc="upper left",
                bbox=[_MARGIN_LEFT, cursor["y"] - height, _MARGIN_RIGHT - _MARGIN_LEFT, height],
                cellLoc="left",
                colLoc="left",
            )
            table.auto_set_font_size(False)
            table.set_fontsize(7.5)
            for cell in table.get_celld().values():
                cell.set_edgecolor("#d1d5db")
                cell.set_linewidth(0.4)
            cursor["y"] -= height + 0.025

        if title:
            _text(title, size=20.0, weight="bold", width=54, gap=0.01)
            if subtitle:
                _text(subtitle, size=10.5, color="#4b5563", width=84, gap=0.02)

        for block in list(blocks or [])[:2_000]:
            if not isinstance(block, dict):
                continue
            kind = str(block.get("type") or "paragraph").casefold()
            if kind == "heading":
                _heading(_as_text(block.get("text")), int(block.get("level") or 1))
            elif kind in ("bullets", "bullet", "unordered_list"):
                for item in block.get("items") or []:
                    _text(f"• {_as_text(item)}", width=88, indent=0.012)
            elif kind in ("numbers", "number", "ordered_list"):
                for index, item in enumerate(block.get("items") or [], start=1):
                    _text(f"{index}. {_as_text(item)}", width=88, indent=0.012)
            elif kind == "table":
                _table(block.get("headers") or [], block.get("rows") or [])
            elif kind == "page_break":
                _new_page()
            else:
                _text(_as_text(block.get("text")))

        _save()
        pdf.close()
        return buffer.getvalue()
    except DocumentError:
        raise
    except Exception as exc:  # noqa: BLE001
        raise DocumentError("REPORT_RENDER_FAILED", f"the PDF report could not be rendered: {exc}") from exc


