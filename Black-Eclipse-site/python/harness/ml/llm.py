"""Optional LoRA fine-tuning of a small local model (torch + transformers + peft).

Scope, stated plainly: this is the *serving-side* half of the generative path. It
fine-tunes a causal LM on a distillation corpus built by `ml.distill`, writes the
adapter to `.black-eclipse/ml/adapters/<name>/`, and leaves a README explaining how
to serve it with any OpenAI-compatible server (Ollama, vLLM) so Eclipse can select
it as a provider.

It is opt-in: none of these libraries is installed by default, and when one is
missing `adapter_support()` says which, `train_adapter` refuses with
MODEL_UNAVAILABLE, and the corpus + a runnable `train_lora.py` are still written so
the work is not lost. Nothing is silently substituted.
"""

from __future__ import annotations

import json
import os
from typing import Any, Optional

from .models import MODEL_UNAVAILABLE, MLError

REQUIRED = ("torch", "transformers", "peft")
MAX_STEPS = 2_000

RUNTIME_SCRIPT = '''"""Fine-tune a LoRA adapter on the corpus next to this file.

Generated by Eclipse. Run it with the interpreter that has torch + transformers +
peft installed:

    python train_lora.py --base <model id> --out adapter

Then serve the adapter with an OpenAI-compatible server (vLLM or Ollama) and point
Eclipse's provider base URL at it. Eclipse never claims a model is trained until
the run completes and the adapter directory contains files.
"""

import json
import sys

from datasets import Dataset
from peft import LoraConfig, get_peft_model
from transformers import (AutoModelForCausalLM, AutoTokenizer,
                          DataCollatorForLanguageModeling, Trainer, TrainingArguments)


def load(path: str):
    rows = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line:
                item = json.loads(line)
                rows.append({"text": "\\n".join(m["content"] for m in item["messages"])})
    return Dataset.from_list(rows)


def main() -> int:
    args = sys.argv[1:]
    base = args[args.index("--base") + 1] if "--base" in args else "Qwen/Qwen2.5-0.5B-Instruct"
    out = args[args.index("--out") + 1] if "--out" in args else "adapter"
    tokenizer = AutoTokenizer.from_pretrained(base)
    model = AutoModelForCausalLM.from_pretrained(base)
    model = get_peft_model(model, LoraConfig(
        r=16, lora_alpha=32, lora_dropout=0.05, task_type="CAUSAL_LM"))

    def tokenize(batch):
        return tokenizer(batch["text"], truncation=True, max_length=512)

    data = load("corpus.jsonl").map(tokenize, batched=True, remove_columns=["text"])
    Trainer(
        model=model,
        args=TrainingArguments(output_dir=out, num_train_epochs=1,
                               per_device_train_batch_size=1,
                               learning_rate=2e-4, logging_steps=10, save_strategy="no"),
        train_dataset=data,
        data_collator=DataCollatorForLanguageModeling(tokenizer, mlm=False),
    ).train()
    model.save_pretrained(out)
    tokenizer.save_pretrained(out)
    print("wrote adapter to", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

README = """# Eclipse LoRA adapter

- `corpus.jsonl` — the distillation corpus this run was built from (one chat
  object per line).
- `train_lora.py` — a runnable fine-tune recipe. It needs `torch`, `transformers`
  and `peft`; install them somewhere with a GPU (or accept CPU speed).
- `manifest.json` — provenance: corpus hash, row count, base model, target.

Serve the resulting adapter with vLLM or Ollama (any OpenAI-compatible endpoint)
and select it in Eclipse's provider settings. Eclipse does not verify the quality
of a fine-tune; evaluate it with the ML lab or your own harness before relying on
it.
"""


def adapter_support() -> tuple[bool, Optional[str]]:
    """Whether the optional fine-tuning stack imports (never raises)."""
    missing: list[str] = []
    for module in REQUIRED:
        try:
            __import__(module)
        except Exception:  # noqa: BLE001 - absence is a supported outcome
            missing.append(module)
    if missing:
        return False, "missing " + ", ".join(missing)
    return True, None


def write_recipe(corpus_path: str, out_dir: str, *, base_model: str,
                 manifest: dict[str, Any]) -> dict[str, Any]:
    """Materialise the corpus + a runnable training script + provenance."""
    os.makedirs(out_dir, exist_ok=True)
    script = os.path.join(out_dir, "train_lora.py")
    with open(script, "w", encoding="utf-8") as handle:
        handle.write(RUNTIME_SCRIPT)
    readme = os.path.join(out_dir, "README.md")
    with open(readme, "w", encoding="utf-8") as handle:
        handle.write(README)
    manifest_path = os.path.join(out_dir, "manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as handle:
        json.dump({"baseModel": base_model, **manifest}, handle, indent=2, sort_keys=True)
    return {"outDir": out_dir, "corpus": corpus_path, "script": script,
            "readme": readme, "manifest": manifest_path}


def train_adapter(corpus_path: str, out_dir: str, *, base_model: str,
                  epochs: int = 1) -> dict[str, Any]:
    """Run the generated recipe in a subprocess. Refuses honestly without deps."""
    import subprocess
    import sys

    available, reason = adapter_support()
    if not available:
        raise MLError(
            MODEL_UNAVAILABLE,
            f"fine-tuning needs the optional stack ({reason}). Install "
            "python/requirements-train.txt plus transformers/peft, or run the "
            "generated train_lora.py where those are available; the corpus and the "
            "recipe are already written.",
            503,
        )
    script = os.path.join(out_dir, "train_lora.py")
    if not os.path.exists(script):
        raise MLError("INVALID_INPUT", "the training recipe has not been written yet", 422)
    completed = subprocess.run(  # noqa: S603 - a local, generated script
        [sys.executable, script, "--base", base_model, "--out", out_dir,
         "--epochs", str(max(1, min(int(epochs), 10)))],
        cwd=out_dir, capture_output=True, text=True, timeout=60 * 60,
    )
    if completed.returncode != 0:
        raise MLError("ML_ERROR",
                       f"fine-tuning failed (exit {completed.returncode}): "
                       f"{(completed.stderr or completed.stdout)[-800:]}", 500)
    files = sorted(os.listdir(out_dir))
    return {"outDir": out_dir, "baseModel": base_model, "files": files,
            "stdout": (completed.stdout or "")[-800:]}


__all__ = ["MAX_STEPS", "REQUIRED", "adapter_support", "train_adapter", "write_recipe"]
